import { normalizeForSearch } from './text-utils.js';

export const DOCUMENT_KINDS = Object.freeze({
  INCOME_REPORT: 'INCOME_REPORT',
  FIXED_INCOME_STATEMENT: 'FIXED_INCOME_STATEMENT',
  QUOTA_FUND_STATEMENT: 'QUOTA_FUND_STATEMENT',
  INVESTMENT_STATEMENT: 'INVESTMENT_STATEMENT',
  REDEMPTION_RECEIPT: 'REDEMPTION_RECEIPT',
  APPLICATION_RECEIPT: 'APPLICATION_RECEIPT',
  POSITION_REPORT: 'POSITION_REPORT',
  BANK_STATEMENT: 'BANK_STATEMENT',
  OFX: 'OFX',
  UNKNOWN: 'UNKNOWN',
});

export function classifyDocument({fileName = '', text = ''}) {
  if (/\.ofx$/i.test(fileName)) return {kind: DOCUMENT_KINDS.OFX, confidence: 1, reasons:['Extensao OFX']};
  const value = normalizeForSearch(`${fileName}\n${text}`).toUpperCase();
  const rules = [
    [DOCUMENT_KINDS.INCOME_REPORT, 0.99, /COMPROVANTE DE RENDIMENTOS|INFORME DE RENDIMENTOS|RENDIMENTOS PAGOS OU CREDITADOS/],
    [DOCUMENT_KINDS.REDEMPTION_RECEIPT, 0.98, /COMPROVANTE DE RESGATE|RESGATE REALIZADO/],
    [DOCUMENT_KINDS.APPLICATION_RECEIPT, 0.96, /COMPROVANTE DE APLICACAO|APLICACAO REALIZADA/],
    [DOCUMENT_KINDS.QUOTA_FUND_STATEMENT, 0.97, /QUANTIDADE DE? COTAS|QTDE DE COTAS|VALOR DA COTA|SALDO COTAS|EXTRATOS - INVESTIMENTOS FUNDOS|CODIGO\s+FUNDO[\s\S]{0,120}CNPJ DO FUNDO/],
    [DOCUMENT_KINDS.INVESTMENT_STATEMENT, 0.95, /DADOS DO RESUMO[\s\S]{0,800}RENDIMENTO APURADO NO[\s\S]{0,800}RESGATES/],
    [DOCUMENT_KINDS.INVESTMENT_STATEMENT, 0.94, /EXTRATO DE INVESTIMENTOS[\s\S]{0,600}\bRDB\b/],
    [DOCUMENT_KINDS.FIXED_INCOME_STATEMENT, 0.96, /EXTRATO DE MOVIMENTACAO DE RENDA FIXA|DEPOSITO A PRAZO|RDC FLEXIVEL|CDB AUTOMATICO|\bCDB\b|\bRDB\b|\bLCI\b|\bLCA\b/],
    [DOCUMENT_KINDS.POSITION_REPORT, 0.85, /POSICAO DE INVESTIMENTOS|POSICAO CONSOLIDADA|POSICAO PARA SAQUE/],
    [DOCUMENT_KINDS.BANK_STATEMENT, 0.75, /EXTRATO DE CONTA|SALDO CONTA CORRENTE|LANCAMENTOS/],
    [DOCUMENT_KINDS.INVESTMENT_STATEMENT, 0.7, /EXTRATO DE APLICACOES|APLICACOES|RESGATES|RENDIMENTO BRUTO|INVESTIMENTOS/],
  ];
  for (const [kind, confidence, regex] of rules) if (regex.test(value)) return {kind, confidence, reasons:[regex.source]};
  return {kind: DOCUMENT_KINDS.UNKNOWN, confidence: 0.2, reasons:['Nenhum padrao forte']};
}
