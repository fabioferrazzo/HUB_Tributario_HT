-- HUB Depto Tributário: Informativos no HUB (recriação do Infos HT)
-- Rode no SQL Editor do Supabase (pode rodar mais de uma vez).
-- Regras:
--   - Todos os usuários ativos veem e baixam os informativos publicados.
--   - Administradores e gestores importam, editam, publicam, arquivam e movem entre pastas.
--   - Só administradores criam/renomeiam/excluem pastas, excluem definitivamente e descartam rascunhos.
--   - Arquivos (imagens, originais e fontes importadas) ficam no bucket privado "hub-informativos".
-- As tabelas não são acessadas diretamente: tudo passa pelas funções inf_* abaixo.

begin;

-- ---------------------------------------------------------------------------------------------
-- Tabelas

create table if not exists public.inf_pastas (
  id bigint generated by default as identity primary key,
  nome text not null check (length(nome) between 1 and 80),
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);
create unique index if not exists inf_pastas_nome_uidx on public.inf_pastas (lower(nome));

create table if not exists public.inf_documentos (
  id text primary key check (id ~ '^[A-Za-z0-9-]{8,64}$'),
  titulo text not null default '' check (length(titulo) <= 180),
  numero text not null default '' check (length(numero) <= 40),
  data_doc text not null default '' check (length(data_doc) <= 20),
  departamento text not null default 'Departamento Tributário' check (length(departamento) <= 100),
  status text not null default 'draft' check (status in ('draft', 'published', 'archived')),
  source_type text not null default 'legacy',
  original_filename text,
  original_sha256 text,
  original_caminho text,
  pasta_id bigint references public.inf_pastas(id) on delete set null,
  pasta_em timestamptz,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now(),
  criado_por uuid references public.profiles(id) on delete set null,
  atualizado_por uuid references public.profiles(id) on delete set null
);
create index if not exists inf_documentos_status_idx on public.inf_documentos (status);

create table if not exists public.inf_conteudo (
  documento_id text primary key references public.inf_documentos(id) on delete cascade,
  rascunho jsonb not null default '{}'::jsonb,
  publicado jsonb not null default '{}'::jsonb,
  rascunho_em timestamptz,
  publicado_em timestamptz,
  atualizado_em timestamptz not null default now()
);

create table if not exists public.inf_versoes (
  id bigint generated by default as identity primary key,
  documento_id text not null references public.inf_documentos(id) on delete cascade,
  numero integer not null,
  snapshot jsonb not null,
  criado_em timestamptz not null default now(),
  criado_por uuid references public.profiles(id) on delete set null,
  criado_por_email text,
  nota text,
  unique (documento_id, numero)
);

create table if not exists public.inf_assets (
  documento_id text not null references public.inf_documentos(id) on delete cascade,
  id text not null check (id ~ '^[A-Za-z0-9_.-]{1,160}$'),
  source_name text not null default '',
  mime_type text not null default 'application/octet-stream',
  caminho text not null,
  sha256 text not null default '',
  tamanho bigint not null default 0,
  criado_em timestamptz not null default now(),
  primary key (documento_id, id)
);

create table if not exists public.inf_fontes (
  id bigint generated by default as identity primary key,
  documento_id text not null references public.inf_documentos(id) on delete cascade,
  revisao integer not null,
  original_filename text not null,
  original_sha256 text not null default '',
  caminho text,
  importado_em timestamptz not null default now(),
  importado_por uuid references public.profiles(id) on delete set null,
  importado_por_email text,
  stats jsonb not null default '{}'::jsonb,
  warnings jsonb not null default '[]'::jsonb,
  unique (documento_id, revisao)
);

do $$
declare t text;
begin
  foreach t in array array['inf_pastas', 'inf_documentos', 'inf_conteudo', 'inf_versoes', 'inf_assets', 'inf_fontes'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on table public.%I from anon, authenticated', t);
  end loop;
end $$;

-- ---------------------------------------------------------------------------------------------
-- Papéis e utilidades

-- 'admin' (administrador do HUB), 'editor' (gestor) ou 'leitor' (demais usuários ativos).
create or replace function public.inf_papel()
returns text language plpgsql stable security definer set search_path = public as $$
declare v_role text;
begin
  if auth.uid() is null or not public.is_active_user() then return null; end if;
  select to_jsonb(p)->>'role' into v_role from public.profiles p where p.id = auth.uid();
  return case when v_role = 'admin' then 'admin' when v_role = 'gestor' then 'editor' else 'leitor' end;
end;
$$;

create or replace function public.inf_exigir(p_minimo text)
returns text language plpgsql stable security definer set search_path = public as $$
declare v text := public.inf_papel();
begin
  if v is null then raise exception 'Sessão inválida ou usuário inativo.' using errcode = '42501'; end if;
  if p_minimo = 'editor' and v not in ('admin', 'editor') then
    raise exception 'Somente administradores e gestores podem alterar informativos.' using errcode = '42501';
  end if;
  if p_minimo = 'admin' and v <> 'admin' then
    raise exception 'Somente o administrador pode fazer isso.' using errcode = '42501';
  end if;
  return v;
end;
$$;

create or replace function public.inf_auditar(p_acao text, p_id text, p_titulo text, p_det jsonb default '{}'::jsonb)
returns void language plpgsql security definer set search_path = public as $$
begin
  if to_regprocedure('public.hub_hist_registrar(text,text,text,text,jsonb)') is not null then
    perform public.hub_hist_registrar('Informativos', p_acao, p_id, p_titulo, coalesce(p_det, '{}'::jsonb));
  end if;
end;
$$;

create or replace function public.inf_doc(p_id text)
returns public.inf_documentos language plpgsql stable security definer set search_path = public as $$
declare v public.inf_documentos;
begin
  select * into v from public.inf_documentos where id = p_id;
  if v.id is null then raise exception 'Informativo não encontrado' using errcode = 'P0002'; end if;
  return v;
end;
$$;

-- Snapshot com os metadados do catálogo preenchendo o que estiver vazio (como merge_document_metadata).
create or replace function public.inf_mesclar_meta(p_snap jsonb, d public.inf_documentos)
returns jsonb language sql stable set search_path = public as $$
  select coalesce(p_snap, '{}'::jsonb) || jsonb_build_object('metadata',
    jsonb_build_object(
      'title', coalesce(nullif(btrim(coalesce(p_snap #>> '{metadata,title}', '')), ''), d.titulo),
      'document_number', coalesce(nullif(btrim(coalesce(p_snap #>> '{metadata,document_number}', '')), ''), d.numero),
      'date', coalesce(nullif(btrim(coalesce(p_snap #>> '{metadata,date}', '')), ''), d.data_doc),
      'department', coalesce(nullif(btrim(coalesce(p_snap #>> '{metadata,department}', '')), ''), d.departamento)
    ) || (coalesce(p_snap->'metadata', '{}'::jsonb) - 'title' - 'document_number' - 'date' - 'department'))
$$;

create or replace function public.inf_doc_json(d public.inf_documentos)
returns jsonb language sql stable security definer set search_path = public as $$
  select jsonb_build_object(
    'id', d.id, 'title', d.titulo, 'document_number', d.numero, 'document_date', d.data_doc, 'department', d.departamento,
    'status', d.status, 'source_type', d.source_type, 'original_filename', d.original_filename, 'original_sha256', d.original_sha256,
    'created_at', d.criado_em, 'updated_at', d.atualizado_em,
    'folder_id', d.pasta_id, 'folder_name', (select nome from public.inf_pastas where id = d.pasta_id),
    'draft_updated_at', c.rascunho_em, 'published_at', c.publicado_em,
    'has_unpublished_changes', case when c.rascunho is distinct from c.publicado then 1 else 0 end,
    'has_published', case when c.publicado_em is not null then 1 else 0 end,
    'version_count', (select count(*) from public.inf_versoes v where v.documento_id = d.id),
    'asset_count', (select count(*) from public.inf_assets a where a.documento_id = d.id),
    'source_revision_count', (select count(*) from public.inf_fontes s where s.documento_id = d.id))
  from public.inf_conteudo c where c.documento_id = d.id
$$;

-- ---------------------------------------------------------------------------------------------
-- Leitura

create or replace function public.inf_sessao()
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare v_papel text := public.inf_papel(); v_nome text; v_email text;
begin
  select p.nome, p.email into v_nome, v_email from public.profiles p where p.id = auth.uid();
  return jsonb_build_object('papel', v_papel, 'nome', coalesce(v_nome, ''), 'email', coalesce(v_email, ''));
end;
$$;

create or replace function public.inf_documentos_listar(p_incluir_arquivados boolean default false)
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare v_papel text := public.inf_exigir('leitor');
begin
  return coalesce((
    select jsonb_agg(public.inf_doc_json(d) order by d.atualizado_em desc, lower(d.titulo))
    from public.inf_documentos d
    where case when v_papel in ('admin', 'editor')
               then (d.status <> 'archived' or coalesce(p_incluir_arquivados, false))
               else d.status = 'published' end), '[]'::jsonb);
end;
$$;

create or replace function public.inf_pastas_listar()
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare v_papel text := public.inf_exigir('leitor');
begin
  return coalesce((
    select jsonb_agg(jsonb_build_object('id', f.id, 'name', f.nome, 'created_at', f.criado_em, 'updated_at', f.atualizado_em,
             'document_count', (select count(*) from public.inf_documentos d where d.pasta_id = f.id
                                 and (v_papel in ('admin', 'editor') or d.status = 'published'))) order by lower(f.nome))
    from public.inf_pastas f), '[]'::jsonb);
end;
$$;

-- p_qual: 'published' ou 'draft'
create or replace function public.inf_documento_obter(p_id text, p_qual text)
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare
  v_papel text := public.inf_exigir('leitor');
  d public.inf_documentos := public.inf_doc(p_id);
  c public.inf_conteudo;
  v jsonb;
begin
  select * into c from public.inf_conteudo where documento_id = p_id;
  if c.documento_id is null then raise exception 'Conteúdo não encontrado' using errcode = 'P0002'; end if;
  if p_qual = 'draft' then
    perform public.inf_exigir('editor');
    v := public.inf_mesclar_meta(c.rascunho, d) || jsonb_build_object('document_id', p_id, 'draft_updated_at', c.rascunho_em);
  else
    if v_papel = 'leitor' and d.status <> 'published' then
      raise exception 'Informativo não encontrado' using errcode = 'P0002';
    end if;
    if c.publicado_em is null and d.status = 'draft' then
      raise exception 'Este informativo ainda está somente em rascunho' using errcode = 'P0001';
    end if;
    v := public.inf_mesclar_meta(c.publicado, d) || jsonb_build_object('document_id', p_id, 'published_at', c.publicado_em);
  end if;
  return v || jsonb_build_object('_doc', public.inf_doc_json(d),
    '_assets', coalesce((select jsonb_object_agg(a.id, jsonb_build_object('caminho', a.caminho, 'mime_type', a.mime_type, 'source_name', a.source_name))
                         from public.inf_assets a where a.documento_id = p_id), '{}'::jsonb));
end;
$$;

create or replace function public.inf_versoes_listar(p_id text)
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare v text := public.inf_exigir('editor'); d public.inf_documentos := public.inf_doc(p_id);
begin
  return coalesce((
    select jsonb_agg(jsonb_build_object('id', x.id, 'version_number', x.numero, 'created_at', x.criado_em, 'note', x.nota,
             'email', coalesce((select email from public.profiles where id = x.criado_por), x.criado_por_email)) order by x.numero desc)
    from (select * from public.inf_versoes where documento_id = p_id order by numero desc limit 100) x), '[]'::jsonb);
end;
$$;

create or replace function public.inf_fontes_listar(p_id text)
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare v text := public.inf_exigir('editor'); d public.inf_documentos := public.inf_doc(p_id);
begin
  return jsonb_build_object(
    'original', jsonb_build_object('caminho', d.original_caminho, 'filename', d.original_filename, 'source_type', d.source_type),
    'sources', coalesce((
      select jsonb_agg(jsonb_build_object('id', s.id, 'revision_number', s.revisao, 'original_filename', s.original_filename,
               'original_sha256', s.original_sha256, 'imported_at', s.importado_em, 'stats', s.stats, 'warnings', s.warnings,
               'email', coalesce((select email from public.profiles where id = s.importado_por), s.importado_por_email)) order by s.revisao desc)
      from public.inf_fontes s where s.documento_id = p_id), '[]'::jsonb));
end;
$$;

-- Todos os publicados (para exportação em lote).
create or replace function public.inf_publicados_conteudo()
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare v text := public.inf_exigir('leitor');
begin
  return coalesce((
    select jsonb_agg(public.inf_mesclar_meta(c.publicado, d) || jsonb_build_object('document_id', d.id, '_doc', public.inf_doc_json(d),
             '_assets', coalesce((select jsonb_object_agg(a.id, jsonb_build_object('caminho', a.caminho, 'mime_type', a.mime_type, 'source_name', a.source_name))
                                  from public.inf_assets a where a.documento_id = d.id), '{}'::jsonb)) order by lower(d.titulo))
    from public.inf_documentos d join public.inf_conteudo c on c.documento_id = d.id
    where d.status = 'published' and c.publicado_em is not null), '[]'::jsonb);
end;
$$;

-- ---------------------------------------------------------------------------------------------
-- Gravação (a tela limpa o conteúdo antes de enviar; aqui ficam as regras e limites)

create or replace function public.inf_validar_snapshot(p jsonb)
returns void language plpgsql immutable set search_path = public as $$
begin
  if p is null or jsonb_typeof(p) <> 'object' then raise exception 'Conteúdo inválido.'; end if;
  if jsonb_typeof(coalesce(p->'elements', '{}'::jsonb)) <> 'object' then raise exception 'Conteúdo inválido (elements).'; end if;
  if octet_length(p::text) > 3000000 then raise exception 'O informativo ficou grande demais para salvar (limite de 3 MB de texto).'; end if;
end;
$$;

create or replace function public.inf_rascunho_salvar(p_id text, p_snapshot jsonb)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v text := public.inf_exigir('editor');
  d public.inf_documentos := public.inf_doc(p_id);
  c public.inf_conteudo;
  m jsonb := coalesce(p_snapshot->'metadata', '{}'::jsonb);
  ts timestamptz := now();
begin
  if d.status = 'archived' then raise exception 'Desarquive o informativo antes desta operação.' using errcode = 'P0001'; end if;
  perform public.inf_validar_snapshot(p_snapshot);
  update public.inf_conteudo set rascunho = p_snapshot, rascunho_em = ts, atualizado_em = ts where documento_id = p_id returning * into c;
  if d.status = 'draft' and c.publicado_em is null then
    update public.inf_documentos set
      titulo = left(btrim(coalesce(nullif(m->>'title', ''), d.titulo)), 180),
      numero = left(btrim(coalesce(nullif(m->>'document_number', ''), d.numero)), 40),
      data_doc = left(btrim(coalesce(nullif(m->>'date', ''), d.data_doc)), 20),
      departamento = left(btrim(coalesce(nullif(m->>'department', ''), d.departamento)), 100),
      atualizado_em = ts, atualizado_por = auth.uid()
    where id = p_id;
  else
    update public.inf_documentos set atualizado_em = ts, atualizado_por = auth.uid() where id = p_id;
  end if;
  return jsonb_build_object('ok', true, 'document_id', p_id, 'saved_at', ts);
end;
$$;

create or replace function public.inf_publicar(p_id text, p_nota text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v text := public.inf_exigir('editor');
  d public.inf_documentos := public.inf_doc(p_id);
  c public.inf_conteudo;
  m jsonb;
  ts timestamptz := now();
  n int;
  vid bigint;
  v_nota text := nullif(left(btrim(coalesce(p_nota, '')), 300), '');
begin
  if d.status = 'archived' then raise exception 'Desarquive o informativo antes desta operação.' using errcode = 'P0001'; end if;
  select * into c from public.inf_conteudo where documento_id = p_id for update;
  m := coalesce(c.rascunho->'metadata', '{}'::jsonb);
  update public.inf_conteudo set publicado = rascunho, publicado_em = ts, atualizado_em = ts where documento_id = p_id;
  update public.inf_documentos set
    titulo = left(btrim(coalesce(nullif(m->>'title', ''), d.titulo)), 180),
    numero = left(btrim(coalesce(nullif(m->>'document_number', ''), d.numero)), 40),
    data_doc = left(btrim(coalesce(nullif(m->>'date', ''), d.data_doc)), 20),
    departamento = left(btrim(coalesce(nullif(m->>'department', ''), d.departamento)), 100),
    status = 'published', atualizado_em = ts, atualizado_por = auth.uid()
  where id = p_id returning * into d;
  select coalesce(max(numero), 0) + 1 into n from public.inf_versoes where documento_id = p_id;
  insert into public.inf_versoes (documento_id, numero, snapshot, criado_em, criado_por, nota)
  values (p_id, n, c.rascunho, ts, auth.uid(), v_nota) returning id into vid;
  perform public.inf_auditar('Publicou', p_id, d.titulo, jsonb_strip_nulls(jsonb_build_object('versao', n, 'nota', v_nota)));
  return jsonb_build_object('ok', true, 'document_id', p_id, 'version_id', vid, 'version_number', n, 'published_at', ts);
end;
$$;

create or replace function public.inf_restaurar(p_id text, p_versao bigint)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v text := public.inf_exigir('editor');
  d public.inf_documentos := public.inf_doc(p_id);
  x public.inf_versoes;
  ts timestamptz := now();
begin
  if d.status = 'archived' then raise exception 'Desarquive o informativo antes desta operação.' using errcode = 'P0001'; end if;
  select * into x from public.inf_versoes where id = p_versao and documento_id = p_id;
  if x.id is null then raise exception 'Versão não encontrada para este informativo' using errcode = 'P0002'; end if;
  update public.inf_conteudo set rascunho = x.snapshot, rascunho_em = ts, atualizado_em = ts where documento_id = p_id;
  update public.inf_documentos set atualizado_em = ts, atualizado_por = auth.uid() where id = p_id;
  perform public.inf_auditar('Restaurou versão no rascunho', p_id, d.titulo, jsonb_build_object('versao', x.numero));
  return jsonb_build_object('ok', true, 'document_id', p_id);
end;
$$;

-- p: {title, document_number, date, department}
create or replace function public.inf_metadados(p_id text, p jsonb)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v text := public.inf_exigir('editor');
  d public.inf_documentos := public.inf_doc(p_id);
  c public.inf_conteudo;
  atual jsonb;
  meta jsonb;
  ts timestamptz := now();
  v_cat boolean;
begin
  if d.status = 'archived' then raise exception 'Desarquive o informativo antes de editar seus metadados.' using errcode = 'P0001'; end if;
  select * into c from public.inf_conteudo where documento_id = p_id;
  atual := coalesce(c.rascunho->'metadata', '{}'::jsonb);
  meta := jsonb_build_object(
    'title', btrim(left(coalesce(case when p ? 'title' then p->>'title' end, atual->>'title', d.titulo, ''), 180)),
    'document_number', btrim(left(coalesce(case when p ? 'document_number' then p->>'document_number' end, atual->>'document_number', d.numero, ''), 40)),
    'date', btrim(left(coalesce(case when p ? 'date' then p->>'date' end, atual->>'date', d.data_doc, ''), 20)),
    'department', btrim(left(coalesce(case when p ? 'department' then p->>'department' end, atual->>'department', d.departamento, ''), 100)));
  if meta->>'title' = '' then raise exception 'O título do informativo não pode ficar vazio.' using errcode = 'P0001'; end if;
  update public.inf_conteudo set rascunho = jsonb_set(coalesce(rascunho, '{}'::jsonb), '{metadata}', meta), rascunho_em = ts, atualizado_em = ts
  where documento_id = p_id;
  v_cat := c.publicado_em is null or d.status = 'draft';
  if v_cat then
    update public.inf_documentos set titulo = meta->>'title', numero = meta->>'document_number', data_doc = meta->>'date',
      departamento = meta->>'department', atualizado_em = ts, atualizado_por = auth.uid() where id = p_id;
  else
    update public.inf_documentos set atualizado_em = ts, atualizado_por = auth.uid() where id = p_id;
  end if;
  perform public.inf_auditar('Editou dados do informativo', p_id, meta->>'title', '{}'::jsonb);
  return jsonb_build_object('ok', true, 'document_id', p_id, 'metadata', meta, 'saved_at', ts, 'catalog_updated', v_cat);
end;
$$;

create or replace function public.inf_arquivar(p_id text, p_arquivar boolean)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v text := public.inf_exigir('editor');
  d public.inf_documentos := public.inf_doc(p_id);
  v_pub timestamptz;
  v_novo text;
begin
  select publicado_em into v_pub from public.inf_conteudo where documento_id = p_id;
  if p_arquivar then
    if d.status = 'archived' then return jsonb_build_object('ok', true, 'document_id', p_id, 'status', 'archived'); end if;
    v_novo := 'archived';
  else
    if d.status <> 'archived' then return jsonb_build_object('ok', true, 'document_id', p_id, 'status', d.status); end if;
    v_novo := case when v_pub is not null then 'published' else 'draft' end;
  end if;
  update public.inf_documentos set status = v_novo, atualizado_em = now(), atualizado_por = auth.uid() where id = p_id;
  perform public.inf_auditar(case when p_arquivar then 'Arquivou' else 'Desarquivou' end, p_id, d.titulo, '{}'::jsonb);
  return jsonb_build_object('ok', true, 'document_id', p_id, 'status', v_novo);
end;
$$;

-- Exclusão definitiva (só administrador; precisa estar arquivado). Devolve os caminhos dos arquivos para a tela apagar.
create or replace function public.inf_excluir(p_id text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v text := public.inf_exigir('admin');
  d public.inf_documentos := public.inf_doc(p_id);
  v_caminhos jsonb;
begin
  if d.status <> 'archived' then raise exception 'Para excluir permanentemente, arquive o informativo primeiro.' using errcode = 'P0001'; end if;
  select to_jsonb(array_remove(array_agg(distinct x), null)) into v_caminhos from (
    select caminho as x from public.inf_assets where documento_id = p_id
    union all select caminho from public.inf_fontes where documento_id = p_id
    union all select d.original_caminho) q;
  delete from public.inf_documentos where id = p_id;
  perform public.inf_auditar('Excluiu definitivamente', p_id, d.titulo, '{}'::jsonb);
  return jsonb_build_object('ok', true, 'document_id', p_id, 'deleted', true, 'caminhos', coalesce(v_caminhos, '[]'::jsonb));
end;
$$;

-- Descarte de rascunho nunca publicado (só administrador).
create or replace function public.inf_descartar(p_id text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v text := public.inf_exigir('admin');
  d public.inf_documentos := public.inf_doc(p_id);
  v_pub timestamptz;
  v_caminhos jsonb;
begin
  select publicado_em into v_pub from public.inf_conteudo where documento_id = p_id;
  if d.status = 'archived' then raise exception 'Desarquive o informativo antes de descartar o rascunho.' using errcode = 'P0001'; end if;
  if d.status <> 'draft' or v_pub is not null then
    raise exception 'Somente rascunhos que nunca foram publicados podem ser descartados diretamente.' using errcode = 'P0001';
  end if;
  select to_jsonb(array_remove(array_agg(distinct x), null)) into v_caminhos from (
    select caminho as x from public.inf_assets where documento_id = p_id
    union all select caminho from public.inf_fontes where documento_id = p_id
    union all select d.original_caminho) q;
  delete from public.inf_documentos where id = p_id;
  perform public.inf_auditar('Descartou rascunho', p_id, d.titulo, '{}'::jsonb);
  return jsonb_build_object('ok', true, 'document_id', p_id, 'discarded', true, 'deleted', true, 'caminhos', coalesce(v_caminhos, '[]'::jsonb));
end;
$$;

create or replace function public.inf_mover(p_id text, p_pasta bigint)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v text := public.inf_exigir('editor');
  d public.inf_documentos := public.inf_doc(p_id);
  v_nome text;
begin
  if p_pasta is null or p_pasta = 0 then
    update public.inf_documentos set pasta_id = null, pasta_em = now() where id = p_id;
  else
    select nome into v_nome from public.inf_pastas where id = p_pasta;
    if v_nome is null then raise exception 'Pasta não encontrada.' using errcode = 'P0001'; end if;
    update public.inf_documentos set pasta_id = p_pasta, pasta_em = now() where id = p_id;
  end if;
  perform public.inf_auditar('Moveu para pasta', p_id, d.titulo, jsonb_build_object('pasta', coalesce(v_nome, 'Sem pasta')));
  return jsonb_build_object('ok', true, 'document_id', p_id, 'folder_id', nullif(p_pasta, 0), 'folder_name', v_nome);
end;
$$;

create or replace function public.inf_pasta_nome(p text)
returns text language plpgsql immutable set search_path = public as $$
declare v text := regexp_replace(btrim(coalesce(p, '')), '\s+', ' ', 'g');
begin
  if v = '' then raise exception 'Informe um nome para a pasta.' using errcode = 'P0001'; end if;
  if length(v) > 80 then raise exception 'O nome da pasta deve ter no máximo 80 caracteres.' using errcode = 'P0001'; end if;
  if lower(v) in ('todos', 'sem pasta', 'rascunhos', 'arquivados', 'pendentes') then
    raise exception 'Este nome é reservado por uma visão automática da Biblioteca.' using errcode = 'P0001';
  end if;
  return v;
end;
$$;

create or replace function public.inf_pasta_salvar(p_id bigint, p_nome text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v text := public.inf_exigir('admin');
  v_nome text := public.inf_pasta_nome(p_nome);
  f public.inf_pastas;
begin
  if exists (select 1 from public.inf_pastas where lower(nome) = lower(v_nome) and id is distinct from p_id) then
    raise exception 'Já existe uma pasta com este nome.' using errcode = 'P0001';
  end if;
  if p_id is null then
    insert into public.inf_pastas (nome) values (v_nome) returning * into f;
  else
    update public.inf_pastas set nome = v_nome, atualizado_em = now() where id = p_id returning * into f;
    if f.id is null then raise exception 'Pasta não encontrada' using errcode = 'P0002'; end if;
  end if;
  return jsonb_build_object('id', f.id, 'name', f.nome, 'created_at', f.criado_em, 'updated_at', f.atualizado_em,
    'document_count', (select count(*) from public.inf_documentos where pasta_id = f.id));
end;
$$;

create or replace function public.inf_pasta_excluir(p_id bigint)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v text := public.inf_exigir('admin'); n int;
begin
  if not exists (select 1 from public.inf_pastas where id = p_id) then raise exception 'Pasta não encontrada' using errcode = 'P0002'; end if;
  select count(*) into n from public.inf_documentos where pasta_id = p_id;
  update public.inf_documentos set pasta_id = null where pasta_id = p_id;
  delete from public.inf_pastas where id = p_id;
  return jsonb_build_object('id', p_id, 'documents_moved_to_unfiled', n);
end;
$$;

-- Novo informativo (pelo Template ou por importação): a tela monta o conteúdo e envia os arquivos antes.
-- p: {id, title, document_number, date, department, source_type, original_filename, original_sha256, original_caminho,
--     folder_id, snapshot, assets:[{id, source_name, mime_type, caminho, sha256, tamanho}], fonte:{original_filename, sha256, caminho, stats, warnings}}
create or replace function public.inf_documento_criar(p jsonb)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v text := public.inf_exigir('editor');
  v_id text := coalesce(p->>'id', '');
  v_snap jsonb := p->'snapshot';
  a jsonb;
  d public.inf_documentos;
begin
  if v_id !~ '^[A-Za-z0-9-]{8,64}$' then raise exception 'Identificador inválido.'; end if;
  if exists (select 1 from public.inf_documentos where id = v_id) then raise exception 'Informativo já existe.'; end if;
  perform public.inf_validar_snapshot(v_snap);
  insert into public.inf_documentos (id, titulo, numero, data_doc, departamento, status, source_type, original_filename, original_sha256,
                                     original_caminho, pasta_id, pasta_em, criado_por, atualizado_por)
  values (v_id, left(btrim(coalesce(nullif(p->>'title', ''), 'Informativo')), 180), left(btrim(coalesce(p->>'document_number', '')), 40),
          left(btrim(coalesce(p->>'date', '')), 20), left(btrim(coalesce(nullif(p->>'department', ''), 'Departamento Tributário')), 100),
          'draft', coalesce(nullif(p->>'source_type', ''), 'template'), nullif(p->>'original_filename', ''), nullif(p->>'original_sha256', ''),
          nullif(p->>'original_caminho', ''),
          (select id from public.inf_pastas where id = nullif(p->>'folder_id', '')::bigint), case when nullif(p->>'folder_id', '') is not null then now() end,
          auth.uid(), auth.uid())
  returning * into d;
  insert into public.inf_conteudo (documento_id, rascunho, publicado, rascunho_em)
  values (v_id, v_snap, case when jsonb_typeof(p->'publicado') = 'object' then p->'publicado' else '{}'::jsonb end, now());
  for a in select * from jsonb_array_elements(coalesce(p->'assets', '[]'::jsonb)) loop
    insert into public.inf_assets (documento_id, id, source_name, mime_type, caminho, sha256, tamanho)
    values (v_id, a->>'id', coalesce(a->>'source_name', ''), coalesce(nullif(a->>'mime_type', ''), 'application/octet-stream'),
            a->>'caminho', coalesce(a->>'sha256', ''), coalesce((a->>'tamanho')::bigint, 0));
  end loop;
  if p ? 'fonte' and jsonb_typeof(p->'fonte') = 'object' then
    insert into public.inf_fontes (documento_id, revisao, original_filename, original_sha256, caminho, importado_por, stats, warnings)
    values (v_id, 1, coalesce(p#>>'{fonte,original_filename}', ''), coalesce(p#>>'{fonte,sha256}', ''), p#>>'{fonte,caminho}', auth.uid(),
            coalesce(p#>'{fonte,stats}', '{}'::jsonb), coalesce(p#>'{fonte,warnings}', '[]'::jsonb));
  end if;
  perform public.inf_auditar(case when d.source_type = 'template' then 'Criou pelo Template' else 'Importou' end, v_id, d.titulo,
                             jsonb_strip_nulls(jsonb_build_object('arquivo', d.original_filename)));
  return jsonb_build_object('ok', true, 'document', public.inf_doc_json(d));
end;
$$;

-- Próximo número "nº NN/AA" do ano (como _next_document_number do Infos HT).
create or replace function public.inf_proximo_numero(p_ano int)
returns text language plpgsql stable security definer set search_path = public as $$
declare v text := public.inf_exigir('editor'); n int; aa text := right(p_ano::text, 2);
begin
  select coalesce(max((regexp_match(numero, '(\d+)\s*/\s*' || aa || '\s*$'))[1]::int), 0) + 1 into n
  from public.inf_documentos where numero ~ ('\d+\s*/\s*' || aa || '\s*$');
  return 'nº ' || lpad(n::text, 2, '0') || '/' || aa;
end;
$$;

-- ---------------------------------------------------------------------------------------------
-- Migração da base do Infos HT (só administrador). Pode ser repetida: atualiza pelo id.
-- p: {pasta, documento:{...campos...}, conteudo:{rascunho, publicado, rascunho_em, publicado_em},
--     versoes:[{numero, snapshot, criado_em, email, nota}], assets:[...], fontes:[...]}
create or replace function public.inf_migrar_documento(p jsonb)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v text := public.inf_exigir('admin');
  doc jsonb := p->'documento';
  v_id text := doc->>'id';
  v_pasta bigint;
  x jsonb;
begin
  if v_id !~ '^[A-Za-z0-9-]{8,64}$' then raise exception 'Identificador inválido: %', v_id; end if;
  -- Só as versões (enviadas em partes, depois do documento)
  if not (doc ? 'status') then
    if not exists (select 1 from public.inf_documentos where id = v_id) then raise exception 'Informativo não encontrado' using errcode = 'P0002'; end if;
    for x in select * from jsonb_array_elements(coalesce(p->'versoes', '[]'::jsonb)) loop
      insert into public.inf_versoes (documento_id, numero, snapshot, criado_em, criado_por, criado_por_email, nota)
      values (v_id, (x->>'numero')::int, x->'snapshot', (x->>'criado_em')::timestamptz,
              (select id from public.profiles where lower(email) = lower(x->>'email') limit 1), x->>'email', nullif(x->>'nota', ''))
      on conflict (documento_id, numero) do update set snapshot = excluded.snapshot, criado_em = excluded.criado_em, nota = excluded.nota;
    end loop;
    return jsonb_build_object('ok', true, 'id', v_id);
  end if;
  if nullif(p->>'pasta', '') is not null then
    select id into v_pasta from public.inf_pastas where lower(nome) = lower(p->>'pasta');
    if v_pasta is null then insert into public.inf_pastas (nome) values (public.inf_pasta_nome(p->>'pasta')) returning id into v_pasta; end if;
  end if;
  insert into public.inf_documentos (id, titulo, numero, data_doc, departamento, status, source_type, original_filename, original_sha256,
                                     original_caminho, pasta_id, pasta_em, criado_em, atualizado_em)
  values (v_id, left(coalesce(doc->>'title', ''), 180), left(coalesce(doc->>'document_number', ''), 40), left(coalesce(doc->>'document_date', ''), 20),
          left(coalesce(doc->>'department', ''), 100), doc->>'status', coalesce(doc->>'source_type', 'legacy'), doc->>'original_filename',
          doc->>'original_sha256', doc->>'original_caminho', v_pasta, case when v_pasta is not null then now() end,
          (doc->>'created_at')::timestamptz, (doc->>'updated_at')::timestamptz)
  on conflict (id) do update set titulo = excluded.titulo, numero = excluded.numero, data_doc = excluded.data_doc, departamento = excluded.departamento,
    status = excluded.status, source_type = excluded.source_type, original_filename = excluded.original_filename,
    original_sha256 = excluded.original_sha256, original_caminho = excluded.original_caminho, pasta_id = excluded.pasta_id,
    criado_em = excluded.criado_em, atualizado_em = excluded.atualizado_em;
  insert into public.inf_conteudo (documento_id, rascunho, publicado, rascunho_em, publicado_em, atualizado_em)
  values (v_id, p#>'{conteudo,rascunho}', p#>'{conteudo,publicado}', (p#>>'{conteudo,rascunho_em}')::timestamptz,
          (p#>>'{conteudo,publicado_em}')::timestamptz, now())
  on conflict (documento_id) do update set rascunho = excluded.rascunho, publicado = excluded.publicado,
    rascunho_em = excluded.rascunho_em, publicado_em = excluded.publicado_em, atualizado_em = now();
  for x in select * from jsonb_array_elements(coalesce(p->'versoes', '[]'::jsonb)) loop
    insert into public.inf_versoes (documento_id, numero, snapshot, criado_em, criado_por, criado_por_email, nota)
    values (v_id, (x->>'numero')::int, x->'snapshot', (x->>'criado_em')::timestamptz,
            (select id from public.profiles where lower(email) = lower(x->>'email') limit 1), x->>'email', nullif(x->>'nota', ''))
    on conflict (documento_id, numero) do update set snapshot = excluded.snapshot, criado_em = excluded.criado_em, nota = excluded.nota;
  end loop;
  for x in select * from jsonb_array_elements(coalesce(p->'assets', '[]'::jsonb)) loop
    insert into public.inf_assets (documento_id, id, source_name, mime_type, caminho, sha256, tamanho, criado_em)
    values (v_id, x->>'id', coalesce(x->>'source_name', ''), x->>'mime_type', x->>'caminho', coalesce(x->>'sha256', ''),
            coalesce((x->>'tamanho')::bigint, 0), coalesce((x->>'criado_em')::timestamptz, now()))
    on conflict (documento_id, id) do update set source_name = excluded.source_name, mime_type = excluded.mime_type, caminho = excluded.caminho,
      sha256 = excluded.sha256, tamanho = excluded.tamanho;
  end loop;
  for x in select * from jsonb_array_elements(coalesce(p->'fontes', '[]'::jsonb)) loop
    insert into public.inf_fontes (documento_id, revisao, original_filename, original_sha256, caminho, importado_em, importado_por, importado_por_email, stats, warnings)
    values (v_id, (x->>'revisao')::int, x->>'original_filename', coalesce(x->>'original_sha256', ''), x->>'caminho',
            (x->>'importado_em')::timestamptz, (select id from public.profiles where lower(email) = lower(x->>'email') limit 1), x->>'email',
            coalesce(x->'stats', '{}'::jsonb), coalesce(x->'warnings', '[]'::jsonb))
    on conflict (documento_id, revisao) do update set original_filename = excluded.original_filename, caminho = excluded.caminho,
      stats = excluded.stats, warnings = excluded.warnings;
  end loop;
  return jsonb_build_object('ok', true, 'id', v_id);
end;
$$;

-- Pastas (inclusive vazias) e histórico do Infos HT (só administrador; não duplica se repetir).
