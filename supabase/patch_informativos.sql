create or replace function public.inf_storage_ler(p_nome text)
returns boolean language plpgsql stable security definer set search_path = public as $$
declare v_papel text := public.inf_papel(); v_doc text := split_part(coalesce(p_nome, ''), '/', 1);
begin
  if v_papel is null then return false; end if;
  if v_papel in ('admin', 'editor') then return true; end if;
  return split_part(p_nome, '/', 2) = 'assets'
     and exists (select 1 from public.inf_documentos where id = v_doc and status = 'published');
end;
$$;

create or replace function public.inf_storage_gravar()
returns boolean language sql stable security definer set search_path = public as $$
  select coalesce(public.inf_papel() in ('admin', 'editor'), false)
$$;

