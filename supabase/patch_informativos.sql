    end if;
  end loop;
  return jsonb_build_object('ok', true, 'criadas', k);
end;
$$;

create or replace function public.inf_migrar_historico(p_itens jsonb)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v text := public.inf_exigir('admin'); x jsonb; k int := 0;
begin
  if to_regclass('public.hub_historico') is null then return jsonb_build_object('ok', true, 'inseridos', 0); end if;
  for x in select * from jsonb_array_elements(coalesce(p_itens, '[]'::jsonb)) loop
    if not exists (select 1 from public.hub_historico h where h.modulo = 'Informativos' and h.quando = (x->>'quando')::timestamptz
                   and h.acao = x->>'acao' and h.entidade_id = coalesce(x->>'id', '')) then
      execute 'insert into public.hub_historico (quando, user_id, modulo, acao, entidade_id, titulo, detalhes) values ($1, $2, ''Informativos'', $3, $4, $5, $6)'
      using (x->>'quando')::timestamptz, (select id from public.profiles where lower(email) = lower(x->>'email') limit 1),
            x->>'acao', coalesce(x->>'id', ''), left(coalesce(nullif(x->>'titulo', ''), '(sem título)'), 200), coalesce(x->'detalhes', '{}'::jsonb);
      k := k + 1;
    end if;
  end loop;
  return jsonb_build_object('ok', true, 'inseridos', k);
end;
$$;

