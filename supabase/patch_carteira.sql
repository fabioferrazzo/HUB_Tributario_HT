-- Início: com base vazia, ou substituindo tudo (p_substituir) quando o ADM confirma.
create or replace function public.cart_migrar_iniciar(p_substituir boolean)
returns jsonb language plpgsql security definer set search_path = public as $$
begin
  perform public.cart_exigir(true);
  perform pg_advisory_xact_lock(hashtext('cart_migracao'));
  if exists (select 1 from public.cart_periodos) or exists (select 1 from public.cart_auditoria) then
    if not coalesce(p_substituir, false) then
      perform public.cart_erro(409, 'A Carteira no HUB já tem dados. Confirme a substituição para importar de novo.');
    end if;
    perform set_config('cart.migracao', 'on', true);
    delete from public.cart_auditoria;
    delete from public.cart_registros;
    delete from public.cart_periodos;
  end if;
  return jsonb_build_object('ok', true);
end;
$$;

-- Lotes: 'periodos', 'registros' ou 'auditoria', com os ids, datas e textos da V2 exatamente como estão no backup.
create or replace function public.cart_migrar_lote(p_tipo text, p_itens jsonb)
returns jsonb language plpgsql security definer set search_path = public as $$
declare n integer;
begin
  perform public.cart_exigir(true);
  if p_itens is null or jsonb_typeof(p_itens) <> 'array' or jsonb_array_length(p_itens) > 5000 then
    perform public.cart_erro(400, 'Lote de migração inválido.');
  end if;
  if p_tipo = 'periodos' then
    insert into public.cart_periodos (id, period_key, year, month, status, source_period_key, created_at, created_by, updated_at)
    select (x->>'id')::bigint, x->>'period_key', (x->>'year')::integer, (x->>'month')::integer, coalesce(x->>'status', 'open'),
      nullif(x->>'source_period_key', ''), coalesce(x->>'created_at', ''), coalesce(x->>'created_by', ''), coalesce(x->>'updated_at', '')
    from jsonb_array_elements(p_itens) x;
  elsif p_tipo = 'registros' then
    insert into public.cart_registros (id, period_id, record_key, row_order, empresa, cnpj, dominio, responsavel_fiscal,
      responsavel_contabil, responsavel_depto_pessoal, regime, socios, fone, email, honorarios, situacao, obs,
      version, created_at, updated_at, updated_by)
    select (x->>'id')::bigint, (x->>'period_id')::bigint, x->>'record_key', coalesce((x->>'row_order')::integer, 0),
      coalesce(x->>'empresa', ''), coalesce(x->>'cnpj', ''), coalesce(x->>'dominio', ''), coalesce(x->>'responsavel_fiscal', ''),
      coalesce(x->>'responsavel_contabil', ''), coalesce(x->>'responsavel_depto_pessoal', ''), coalesce(x->>'regime', ''),
      coalesce(x->>'socios', ''), coalesce(x->>'fone', ''), coalesce(x->>'email', ''), coalesce(x->>'honorarios', ''),
      coalesce(x->>'situacao', ''), coalesce(x->>'obs', ''),
      coalesce((x->>'version')::integer, 1), coalesce(x->>'created_at', ''), coalesce(x->>'updated_at', ''), coalesce(x->>'updated_by', '')
    from jsonb_array_elements(p_itens) x;
  elsif p_tipo = 'auditoria' then
    insert into public.cart_auditoria (id, event_uuid, batch_uuid, period_id, period_key, record_id, record_key, username, action, field,
      old_value, new_value, version_before, version_after, occurred_at, server_instance, row_ref, empresa_snapshot, cnpj_snapshot,
      source_event_id, source_batch_id)
    select (x->>'id')::bigint, x->>'event_uuid', coalesce(x->>'batch_uuid', ''), nullif(x->>'period_id', '')::bigint, x->>'period_key',
      nullif(x->>'record_id', '')::bigint, coalesce(x->>'record_key', ''), coalesce(x->>'username', ''), x->>'action', x->>'field',
      coalesce(x->>'old_value', ''), coalesce(x->>'new_value', ''), nullif(x->>'version_before', '')::integer,
      nullif(x->>'version_after', '')::integer, coalesce(x->>'occurred_at', ''), coalesce(x->>'server_instance', ''),
      coalesce(x->>'row_ref', ''), coalesce(x->>'empresa_snapshot', ''), coalesce(x->>'cnpj_snapshot', ''),
      coalesce(x->>'source_event_id', ''), coalesce(x->>'source_batch_id', '')
    from jsonb_array_elements(p_itens) x;
  else
    perform public.cart_erro(400, 'Tipo de lote inválido.');
  end if;
  get diagnostics n = row_count;
  return jsonb_build_object('ok', true, 'inseridos', n);
end;
$$;

-- Conclusão: confere as contagens com as do arquivo e acerta as sequências (ids novos nunca repetem ids antigos).
create or replace function public.cart_migrar_concluir(p_resumo jsonb)
returns jsonb language plpgsql security definer set search_path = public as $$
declare c jsonb; e jsonb := coalesce(p_resumo->'counts', '{}'::jsonb);
begin
  perform public.cart_exigir(true);
  c := jsonb_build_object('periods', (select count(*) from public.cart_periodos), 'records', (select count(*) from public.cart_registros),
    'audit', (select count(*) from public.cart_auditoria));
  if (c->>'periods') <> coalesce(e->>'periods', '') or (c->>'records') <> coalesce(e->>'records', '') or (c->>'audit') <> coalesce(e->>'audit', '') then
    perform public.cart_erro(409, 'As contagens no HUB não conferem com o arquivo. Repita a importação.', jsonb_build_object('hub', c, 'arquivo', e));
  end if;
  perform setval(pg_get_serial_sequence('public.cart_periodos', 'id'),
    greatest(coalesce((select max(id) from public.cart_periodos), 0), coalesce((e->>'seq_periods')::bigint, 0), 1));
  perform setval(pg_get_serial_sequence('public.cart_registros', 'id'),
    greatest(coalesce((select max(id) from public.cart_registros), 0), coalesce((select max(record_id) from public.cart_auditoria), 0),
      coalesce((e->>'seq_records')::bigint, 0), 1));
  perform setval(pg_get_serial_sequence('public.cart_auditoria', 'id'),
    greatest(coalesce((select max(id) from public.cart_auditoria), 0), coalesce((e->>'seq_audit')::bigint, 0), 1));
  insert into public.cart_migracoes (origem, arquivo, arquivo_sha256, origem_info, contagens, importado_por)
  values ('Carteira de Clientes V2 (SQLite)', left(coalesce(p_resumo->>'arquivo', ''), 200), coalesce(p_resumo->>'sha256', ''),
    coalesce(p_resumo->'origem', '{}'::jsonb), c, auth.uid());
  perform public.hub_hist_registrar('Carteira de Clientes', 'Importou a base da V2', '', left(coalesce(p_resumo->>'arquivo', 'base da V2'), 200), c);
  return jsonb_build_object('ok', true, 'counts', c);
end;
$$;

