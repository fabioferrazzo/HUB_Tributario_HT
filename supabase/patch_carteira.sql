create or replace function public.cart_registros_listar(p_period text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_per public.cart_periodos;
begin
  perform public.cart_exigir(false);
  select * into v_per from public.cart_periodos where period_key = p_period;
  if not found then perform public.cart_erro(404, 'Competência não encontrada.'); end if;
  return jsonb_build_object('ok', true, 'period', public.cart_periodo_json(v_per),
    'total', (select count(*) from public.cart_registros r where r.period_id = v_per.id),
    'records', coalesce((select jsonb_agg(public.cart_registro_json(x) order by x.row_order, x.id)
      from (select * from public.cart_registros r where r.period_id = v_per.id order by r.row_order, r.id limit 2000) x), '[]'::jsonb));
end;
$$;

create or replace function public.cart_auditoria_listar(p_period text, p_record_id bigint default null)
returns jsonb language plpgsql security definer set search_path = public as $$
begin
  perform public.cart_exigir(false);
  return jsonb_build_object('ok', true,
    'total', (select count(*) from public.cart_auditoria a where a.period_key = p_period and (p_record_id is null or a.record_id = p_record_id)),
    'audit', coalesce((select jsonb_agg(x.j order by x.id) from (
      select a.id, jsonb_build_object('id', a.id, 'event_uuid', a.event_uuid, 'batch_uuid', a.batch_uuid, 'period_id', a.period_id,
        'period_key', a.period_key, 'record_id', a.record_id, 'record_key', a.record_key, 'username', a.username, 'action', a.action,
        'field', a.field, 'old_value', a.old_value, 'new_value', a.new_value, 'version_before', a.version_before,
        'version_after', a.version_after, 'occurred_at', a.occurred_at, 'server_instance', a.server_instance,
        'row_ref', a.row_ref, 'empresa_snapshot', a.empresa_snapshot, 'cnpj_snapshot', a.cnpj_snapshot,
        'source_event_id', a.source_event_id, 'source_batch_id', a.source_batch_id,
        'current_empresa', r.empresa, 'current_cnpj', r.cnpj, 'current_row_order', r.row_order) as j
      from public.cart_auditoria a left join public.cart_registros r on r.id = a.record_id
      where a.period_key = p_period and (p_record_id is null or a.record_id = p_record_id)
      order by a.id limit 5000) x), '[]'::jsonb));
end;
$$;

