-- HUB Depto Tributário: Carteira de Clientes no HUB (recriação da Carteira de Clientes V2 2.1.0 com a base no Supabase).
-- Rode no SQL Editor do Supabase (pode rodar mais de uma vez; não apaga dados).
--
-- Mesmas regras do servidor da V2 (server.py):
-- - competências mensais (AAAA-MM) com as empresas de cada mês;
-- - gravação em lote com controle de versão por linha e conflito só quando a MESMA célula foi alterada por outro usuário;
-- - auditoria append-only (inclusão, edição, exclusão, importação XLSX);
-- - ADM edita; usuário comum só consulta.
-- Acesso: administradores do HUB são ADM; os demais usuários ativos do HUB consultam, e o ADM pode torná-los ADM
-- ou retirar o acesso. Tabelas fechadas: tudo passa pelas funções cart_* abaixo.

begin;

-- Datas guardadas como texto, como no SQLite da V2 (a base importada mantém as datas originais).
-- Formato do servidor da V2 (ISO em UTC, sem frações): 2026-09-14T12:00:00+00:00
create or replace function public.cart_ts(t timestamptz)
returns text language sql immutable set search_path = public as $$
  select case when t is null then null else to_char(t at time zone 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS') || '+00:00' end
$$;

create table if not exists public.cart_periodos (
  id bigint generated by default as identity primary key,
  period_key text not null unique check (period_key ~ '^\d{4}-\d{2}$'),
  year integer not null,
  month integer not null check (month between 1 and 12),
  status text not null default 'open' check (status in ('open', 'closed')),
  source_period_key text,
  created_at text not null default public.cart_ts(now()),
  created_by text not null default '',
  updated_at text not null default public.cart_ts(now())
);

create table if not exists public.cart_registros (
  id bigint generated by default as identity primary key,
  period_id bigint not null references public.cart_periodos(id) on delete cascade,
  record_key text not null,
  row_order integer not null default 0,
  empresa text not null default '',
  cnpj text not null default '',
  dominio text not null default '',
  responsavel_fiscal text not null default '',
  responsavel_contabil text not null default '',
  responsavel_depto_pessoal text not null default '',
  regime text not null default '',
  socios text not null default '',
  fone text not null default '',
  email text not null default '',
  honorarios text not null default '',
  situacao text not null default '',
  obs text not null default '',
  version integer not null default 1 check (version >= 1),
  created_at text not null default public.cart_ts(now()),
  updated_at text not null default public.cart_ts(now()),
  updated_by text not null default '',
  unique (period_id, record_key)
);
create index if not exists cart_registros_periodo_ordem on public.cart_registros (period_id, row_order, id);

create table if not exists public.cart_auditoria (
  id bigint generated by default as identity primary key,
  event_uuid text not null unique,
  batch_uuid text not null,
  period_id bigint references public.cart_periodos(id),
  period_key text not null,
  record_id bigint,
  record_key text not null default '',
  username text not null,
  action text not null,
  field text not null,
  old_value text not null default '',
  new_value text not null default '',
  version_before integer,
  version_after integer,
  occurred_at text not null default public.cart_ts(now()),
  server_instance text not null default '',
  row_ref text not null default '',
  empresa_snapshot text not null default '',
  cnpj_snapshot text not null default '',
  source_event_id text not null default '',
  source_batch_id text not null default '',
  user_id uuid references public.profiles(id) on delete set null
);
create index if not exists cart_auditoria_periodo on public.cart_auditoria (period_key, id);
create index if not exists cart_auditoria_registro on public.cart_auditoria (record_id, id);

-- Auditoria append-only (como os gatilhos do SQLite). Só a importação da base da V2 pode substituir tudo.
create or replace function public.cart_auditoria_imutavel()
returns trigger language plpgsql as $$
begin
  if coalesce(current_setting('cart.migracao', true), '') = 'on' then
    return case when tg_op = 'DELETE' then old else new end;
  end if;
  raise exception 'audit_log is append-only: % forbidden', tg_op;
end;
$$;
drop trigger if exists cart_auditoria_sem_update on public.cart_auditoria;
create trigger cart_auditoria_sem_update before update on public.cart_auditoria for each row execute function public.cart_auditoria_imutavel();
drop trigger if exists cart_auditoria_sem_delete on public.cart_auditoria;
create trigger cart_auditoria_sem_delete before delete on public.cart_auditoria for each row execute function public.cart_auditoria_imutavel();

-- Perfil de cada usuário do HUB na Carteira (sem linha = consulta). Administradores do HUB são sempre ADM.
create table if not exists public.cart_acessos (
  user_id uuid primary key references public.profiles(id) on delete cascade,
  papel text not null check (papel in ('admin', 'viewer', 'bloqueado')),
  atualizado_em timestamptz not null default now(),
  atualizado_por uuid references public.profiles(id) on delete set null
);

create table if not exists public.cart_migracoes (
  id bigint generated always as identity primary key,
  origem text not null,
  arquivo text not null default '',
  arquivo_sha256 text not null default '',
  origem_info jsonb not null default '{}'::jsonb,
  contagens jsonb not null default '{}'::jsonb,
  importado_em timestamptz not null default now(),
  importado_por uuid references public.profiles(id) on delete set null
);

alter table public.cart_periodos enable row level security;
alter table public.cart_registros enable row level security;
alter table public.cart_auditoria enable row level security;
alter table public.cart_acessos enable row level security;
alter table public.cart_migracoes enable row level security;
revoke all on table public.cart_periodos, public.cart_registros, public.cart_auditoria, public.cart_acessos, public.cart_migracoes from anon, authenticated;

-- ------------------------------------------------------------------------------------------- utilidades

create or replace function public.cart_erro(p_status integer, p_mensagem text, p_detalhes jsonb default null)
returns void language plpgsql set search_path = public as $$
begin
  -- HTnnn: a ponte do app devolve o mesmo código HTTP do servidor da V2 (400, 403, 404, 409)
  raise exception using errcode = 'HT' || p_status::text, message = p_mensagem,
    detail = coalesce(p_detalhes::text, '');
end;
$$;

-- Papel na Carteira: 'admin', 'viewer' ou null (sem acesso).
create or replace function public.cart_papel()
returns text language plpgsql stable security definer set search_path = public as $$
declare v_role text; v_papel text;
begin
  if auth.uid() is null or not public.is_active_user() then return null; end if;
  select to_jsonb(p)->>'role' into v_role from public.profiles p where p.id = auth.uid();
  if v_role = 'admin' then return 'admin'; end if;
  select a.papel into v_papel from public.cart_acessos a where a.user_id = auth.uid();
  if v_papel = 'bloqueado' then return null; end if;
  return coalesce(v_papel, 'viewer');
end;
$$;

-- Nome gravado na auditoria e em "atualizado por" (no lugar do usuário local da V2)
create or replace function public.cart_usuario_nome()
returns text language sql stable security definer set search_path = public as $$
  select coalesce(nullif(btrim(p.nome), ''), nullif(btrim(p.email), ''), 'usuário do HUB') from public.profiles p where p.id = auth.uid()
$$;

create or replace function public.cart_exigir(p_admin boolean default false)
returns text language plpgsql stable security definer set search_path = public as $$
declare v_papel text := public.cart_papel();
begin
  if v_papel is null then
    perform public.cart_erro(403, 'Você não tem acesso à Carteira de Clientes. Peça ao administrador do HUB.');
  end if;
  if p_admin and v_papel <> 'admin' then perform public.cart_erro(403, 'Operação exclusiva de ADM.'); end if;
  return v_papel;
end;
$$;

create or replace function public.cart_rotulo(p_campo text)
returns text language sql immutable set search_path = public as $$
  select case p_campo
    when 'empresa' then 'Empresa' when 'cnpj' then 'CNPJ' when 'dominio' then 'Domínio'
    when 'responsavel_fiscal' then 'Responsável Fiscal' when 'responsavel_contabil' then 'Responsável Contábil'
    when 'responsavel_depto_pessoal' then 'Responsável Depto Pessoal' when 'regime' then 'Regime'
    when 'socios' then 'Sócios' when 'fone' then 'Fone' when 'email' then 'E-mail'
    when 'honorarios' then 'Honorários' when 'situacao' then 'Situação' when 'obs' then 'Obs.' end
$$;

create or replace function public.cart_campos()
returns text[] language sql immutable as $$
  select array['empresa','cnpj','dominio','responsavel_fiscal','responsavel_contabil','responsavel_depto_pessoal',
               'regime','socios','fone','email','honorarios','situacao','obs']
$$;

-- clean_field do servidor: campo permitido, texto, limite de tamanho por campo
create or replace function public.cart_limpar(p_campo text, p_valor jsonb)
returns text language plpgsql immutable set search_path = public as $$
declare v text; v_max integer;
begin
  if not (p_campo = any(public.cart_campos())) then perform public.cart_erro(400, 'Campo não permitido: ' || coalesce(p_campo, '')); end if;
  if p_valor is null or jsonb_typeof(p_valor) = 'null' then v := '';
  elsif jsonb_typeof(p_valor) = 'string' then v := p_valor #>> '{}';
  elsif jsonb_typeof(p_valor) = 'boolean' then v := case when p_valor::text = 'true' then 'True' else 'False' end;
  else v := p_valor::text;
  end if;
  v_max := case p_campo when 'empresa' then 500 when 'cnpj' then 40 when 'dominio' then 80 when 'regime' then 50
    when 'fone' then 100 when 'email' then 320 when 'honorarios' then 80 when 'situacao' then 80 when 'obs' then 4000 else 1000 end;
  if char_length(v) > v_max then perform public.cart_erro(400, 'Valor excede o limite do campo ' || public.cart_rotulo(p_campo) || '.'); end if;
  return v;
end;
$$;

