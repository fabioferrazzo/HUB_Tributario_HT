-- apply_save_batch do servidor: update / insert / delete em uma transação
-- p_changes em json (não jsonb) para manter a ordem dos campos enviados, como o servidor (auditoria na mesma ordem)
drop function if exists public.cart_salvar(text, jsonb);
create or replace function public.cart_salvar(p_period text, p_changes json)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_usuario text;
  v_per public.cart_periodos;
  v_batch uuid := gen_random_uuid();
  v_res jsonb := '[]'::jsonb;
  ch json; v_tipo text; v_id bigint; v_esperada integer;
  v_row public.cart_registros; v_fresh public.cart_registros;
  v_in json; v_base jsonb; v_lim jsonb; v_chaves text[]; k text; v_val text; v_atual text; v_conf text[]; v_alt text[];
  v_mud jsonb; v_ordem integer; n_ed integer := 0; n_inc integer := 0; n_exc integer := 0;
begin
  perform public.cart_exigir(true);
  v_usuario := public.cart_usuario_nome();
  if p_changes is null or json_typeof(p_changes) <> 'array' or json_array_length(p_changes) = 0 then
    perform public.cart_erro(400, 'Nenhuma alteração informada.');
  end if;
  if json_array_length(p_changes) > 2000 then perform public.cart_erro(400, 'Lote muito grande.'); end if;
  select * into v_per from public.cart_periodos where period_key = p_period for update;
  if not found then perform public.cart_erro(404, 'Competência não encontrada.'); end if;
  if v_per.status <> 'open' then perform public.cart_erro(409, 'Competência fechada para edição.'); end if;

  for ch in select * from json_array_elements(p_changes) loop
    if json_typeof(ch) <> 'object' then perform public.cart_erro(400, 'Alteração inválida.'); end if;
    v_tipo := lower(coalesce(ch->>'type', 'update'));
    if v_tipo = 'update' then
      v_id := coalesce(nullif(ch->>'record_id', '')::bigint, 0);
      v_esperada := coalesce(nullif(ch->>'expected_version', '')::integer, 0);
      select * into v_row from public.cart_registros where id = v_id and period_id = v_per.id for update;
      if not found then perform public.cart_erro(404, 'Registro ' || v_id || ' não encontrado.'); end if;
      v_in := ch->'fields'; v_base := (ch->'base_fields')::jsonb;
      if v_in is null or json_typeof(v_in) <> 'object' then perform public.cart_erro(400, 'Nenhum campo informado para edicao.'); end if;
      -- chaves na ordem enviada (a última repetida vale, como num dict do Python)
      select coalesce(array_agg(key order by n), '{}') into v_chaves from (
        select key, min(n) as n from json_object_keys(v_in) with ordinality o(key, n) group by key) t;
      if coalesce(array_length(v_chaves, 1), 0) = 0 then perform public.cart_erro(400, 'Nenhum campo informado para edicao.'); end if;
      if v_base is null or jsonb_typeof(v_base) <> 'object' then v_base := '{}'::jsonb; end if;
      v_lim := '{}'::jsonb;
      foreach k in array v_chaves loop
        v_lim := v_lim || jsonb_build_object(k, public.cart_limpar(k, (v_in::jsonb)->k));
      end loop;
      -- conflito por campo: versão antiga só é problema quando a mesma célula mudou no servidor
      if v_row.version <> v_esperada then
        v_conf := '{}';
        foreach k in array v_chaves loop
          if not (v_base ? k) then v_conf := v_conf || k; continue; end if;
          v_val := public.cart_limpar(k, v_base->k);
          v_atual := coalesce(to_jsonb(v_row)->>k, '');
          if v_atual <> v_val and v_atual <> (v_lim->>k) then v_conf := v_conf || k; end if;
        end loop;
        if coalesce(array_length(v_conf, 1), 0) > 0 then
          perform public.cart_erro(409, 'O mesmo campo foi alterado por outro usuario.', jsonb_build_object(
            'record_id', v_id, 'expected_version', v_esperada, 'current_version', v_row.version,
            'current_record', public.cart_registro_json(v_row),
            'conflict_fields', (select jsonb_agg(public.cart_rotulo(c)) from unnest(v_conf) c),
            'conflict_field_keys', to_jsonb(v_conf)));
        end if;
      end if;
      v_mud := '{}'::jsonb; v_alt := '{}';
      foreach k in array v_chaves loop
        if coalesce(to_jsonb(v_row)->>k, '') <> (v_lim->>k) then v_mud := v_mud || jsonb_build_object(k, v_lim->>k); v_alt := v_alt || k; end if;
      end loop;
      if v_mud = '{}'::jsonb then
        v_res := v_res || jsonb_build_object('type', 'update', 'record_id', v_id, 'version', v_row.version, 'changed_fields', 0);
        continue;
      end if;
      update public.cart_registros set
        empresa = coalesce(v_mud->>'empresa', empresa), cnpj = coalesce(v_mud->>'cnpj', cnpj), dominio = coalesce(v_mud->>'dominio', dominio),
        responsavel_fiscal = coalesce(v_mud->>'responsavel_fiscal', responsavel_fiscal),
        responsavel_contabil = coalesce(v_mud->>'responsavel_contabil', responsavel_contabil),
        responsavel_depto_pessoal = coalesce(v_mud->>'responsavel_depto_pessoal', responsavel_depto_pessoal),
        regime = coalesce(v_mud->>'regime', regime), socios = coalesce(v_mud->>'socios', socios), fone = coalesce(v_mud->>'fone', fone),
        email = coalesce(v_mud->>'email', email), honorarios = coalesce(v_mud->>'honorarios', honorarios),
        situacao = coalesce(v_mud->>'situacao', situacao), obs = coalesce(v_mud->>'obs', obs),
        version = v_row.version + 1, updated_at = public.cart_ts(now()), updated_by = v_usuario
      where id = v_id and period_id = v_per.id and version = v_row.version
      returning * into v_fresh;
      if not found then perform public.cart_erro(409, 'Conflito detectado durante a gravação.', jsonb_build_object('record_id', v_id)); end if;
      -- auditoria na ordem dos campos enviados (como o servidor)
      foreach k in array v_alt loop
        perform public.cart_auditar(v_batch, v_per, v_fresh, v_usuario, 'Edição', public.cart_rotulo(k),
          coalesce(to_jsonb(v_row)->>k, ''), v_mud->>k, v_row.version, v_row.version + 1);
      end loop;
      n_ed := n_ed + 1;
      v_res := v_res || jsonb_build_object('type', 'update', 'record_id', v_id, 'version', v_row.version + 1,
        'changed_fields', array_length(v_alt, 1));

    elsif v_tipo = 'insert' then
      v_base := coalesce((ch->'fields')::jsonb, '{}'::jsonb);
      if jsonb_typeof(v_base) <> 'object' then v_base := '{}'::jsonb; end if;
      v_lim := '{}'::jsonb;
      foreach k in array public.cart_campos() loop
        v_lim := v_lim || jsonb_build_object(k, public.cart_limpar(k, v_base->k));
      end loop;
      v_ordem := coalesce(nullif(ch->>'row_order', '')::integer, 0);
      if v_ordem <= 0 then
        select coalesce(max(row_order), 0) + 1 into v_ordem from public.cart_registros where period_id = v_per.id;
      end if;
      insert into public.cart_registros (period_id, record_key, row_order, empresa, cnpj, dominio, responsavel_fiscal,
        responsavel_contabil, responsavel_depto_pessoal, regime, socios, fone, email, honorarios, situacao, obs,
        version, created_at, updated_at, updated_by)
      values (v_per.id, gen_random_uuid()::text, v_ordem, v_lim->>'empresa', v_lim->>'cnpj', v_lim->>'dominio',
        v_lim->>'responsavel_fiscal', v_lim->>'responsavel_contabil', v_lim->>'responsavel_depto_pessoal', v_lim->>'regime',
        v_lim->>'socios', v_lim->>'fone', v_lim->>'email', v_lim->>'honorarios', v_lim->>'situacao', v_lim->>'obs',
        1, public.cart_ts(now()), public.cart_ts(now()), v_usuario)
      returning * into v_fresh;
      perform public.cart_auditar(v_batch, v_per, v_fresh, v_usuario, 'Inclusão', 'Linha/empresa', '', public.cart_resumo(v_fresh), null, 1);
      n_inc := n_inc + 1;
      v_res := v_res || jsonb_build_object('type', 'insert', 'record_id', v_fresh.id, 'record_key', v_fresh.record_key, 'version', 1);

    elsif v_tipo = 'delete' then
      v_id := coalesce(nullif(ch->>'record_id', '')::bigint, 0);
      v_esperada := coalesce(nullif(ch->>'expected_version', '')::integer, 0);
      select * into v_row from public.cart_registros where id = v_id and period_id = v_per.id for update;
      if not found then perform public.cart_erro(404, 'Registro ' || v_id || ' não encontrado.'); end if;
      if v_row.version <> v_esperada then
        perform public.cart_erro(409, 'O registro foi alterado por outro usuário.', jsonb_build_object(
          'record_id', v_id, 'expected_version', v_esperada, 'current_version', v_row.version,
          'current_record', public.cart_registro_json(v_row)));
      end if;
      perform public.cart_auditar(v_batch, v_per, v_row, v_usuario, 'Exclusão', 'Linha/empresa', public.cart_resumo(v_row), '', v_row.version, null);
      delete from public.cart_registros where id = v_id and period_id = v_per.id and version = v_row.version;
      if not found then perform public.cart_erro(409, 'Conflito detectado durante a exclusão.', jsonb_build_object('record_id', v_id)); end if;
      n_exc := n_exc + 1;
      v_res := v_res || jsonb_build_object('type', 'delete', 'record_id', v_id);
    else
      perform public.cart_erro(400, 'Tipo de alteração inválido: ' || v_tipo);
    end if;
  end loop;

  update public.cart_periodos set updated_at = public.cart_ts(now()) where id = v_per.id;
  if n_ed + n_inc + n_exc > 0 then
    perform public.hub_hist_registrar('Carteira de Clientes', 'Salvou alterações', v_per.period_key,
      'Competência ' || substr(v_per.period_key, 6, 2) || '/' || substr(v_per.period_key, 1, 4),
      jsonb_build_object('empresas_editadas', n_ed, 'inclusoes', n_inc, 'exclusoes', n_exc));
  end if;
  return jsonb_build_object('ok', true, 'batch_uuid', v_batch, 'results', v_res);
end;
$$;

-- create_period do servidor: nova competência copiando a relação da origem
create or replace function public.cart_competencia_criar(p_period text, p_source text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_usuario text; v_src public.cart_periodos; v_new public.cart_periodos; v_n integer := 0;
  v_ano integer; v_mes integer;
begin
  perform public.cart_exigir(true);
  v_usuario := public.cart_usuario_nome();
  p_period := btrim(coalesce(p_period, '')); p_source := btrim(coalesce(p_source, ''));
  if p_period !~ '^\d{4}-\d{2}$' then perform public.cart_erro(400, 'Competência inválida. Use AAAA-MM.'); end if;
  v_ano := split_part(p_period, '-', 1)::integer; v_mes := split_part(p_period, '-', 2)::integer;
  if v_mes < 1 or v_mes > 12 then perform public.cart_erro(400, 'Mês inválido.'); end if;
  perform pg_advisory_xact_lock(hashtext('cart_competencia'));
  if exists (select 1 from public.cart_periodos where period_key = p_period) then perform public.cart_erro(409, 'Competência já existe.'); end if;
  if p_source <> '' then
    select * into v_src from public.cart_periodos where period_key = p_source;
    if not found then perform public.cart_erro(404, 'Competência de origem não encontrada.'); end if;
  end if;
  insert into public.cart_periodos (period_key, year, month, status, source_period_key, created_at, created_by, updated_at)
  values (p_period, v_ano, v_mes, 'open', nullif(p_source, ''), public.cart_ts(now()), v_usuario, public.cart_ts(now())) returning * into v_new;
  if v_src.id is not null then
    insert into public.cart_registros (period_id, record_key, row_order, empresa, cnpj, dominio, responsavel_fiscal,
      responsavel_contabil, responsavel_depto_pessoal, regime, socios, fone, email, honorarios, situacao, obs,
      version, created_at, updated_at, updated_by)
    select v_new.id, gen_random_uuid()::text, r.row_order, r.empresa, r.cnpj, r.dominio, r.responsavel_fiscal,
      r.responsavel_contabil, r.responsavel_depto_pessoal, r.regime, r.socios, r.fone, r.email, r.honorarios, r.situacao, r.obs,
      1, public.cart_ts(now()), public.cart_ts(now()), v_usuario
    from public.cart_registros r where r.period_id = v_src.id order by r.row_order, r.id;
    get diagnostics v_n = row_count;
  end if;
  perform public.hub_hist_registrar('Carteira de Clientes', 'Criou competência', p_period,
    'Competência ' || substr(p_period, 6, 2) || '/' || substr(p_period, 1, 4),
    jsonb_build_object('copiada_de', nullif(p_source, ''), 'empresas', v_n));
  return jsonb_build_object('ok', true, 'period_key', p_period, 'copied_records', v_n, 'batch_uuid', gen_random_uuid()::text);
end;
$$;

-- replace_period_from_xlsx do servidor (o XLSX é lido no navegador, com as mesmas regras de parse_xlsx_records)
create or replace function public.cart_importar_xlsx(p_period text, p_records jsonb, p_filename text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_usuario text; v_per public.cart_periodos; v_ant integer; v_batch uuid := gen_random_uuid();
  x jsonb; i integer := 0; k text; v_lim jsonb; v_nome text;
begin
  perform public.cart_exigir(true);
  v_usuario := public.cart_usuario_nome();
  select * into v_per from public.cart_periodos where period_key = p_period for update;
  if not found then perform public.cart_erro(404, 'Competência não encontrada.'); end if;
  if v_per.status <> 'open' then perform public.cart_erro(409, 'Competência fechada para edição.'); end if;
  if p_records is null or jsonb_typeof(p_records) <> 'array' or jsonb_array_length(p_records) = 0 then
    perform public.cart_erro(400, 'Nenhum registro válido para importar.');
  end if;
  if jsonb_array_length(p_records) > 5000 then perform public.cart_erro(400, 'O XLSX excede o limite de 5000 empresas.'); end if;
  v_nome := regexp_replace(coalesce(nullif(btrim(p_filename), ''), 'importacao.xlsx'), '^.*[\\/]', '');
  select count(*) into v_ant from public.cart_registros where period_id = v_per.id;
  delete from public.cart_registros where period_id = v_per.id;
  for x in select * from jsonb_array_elements(p_records) loop
    i := i + 1;
    v_lim := '{}'::jsonb;
    foreach k in array public.cart_campos() loop v_lim := v_lim || jsonb_build_object(k, public.cart_limpar(k, x->k)); end loop;
    if btrim(v_lim->>'empresa') = '' then perform public.cart_erro(400, 'Registro ' || i || ': a coluna Empresa não pode ficar vazia.'); end if;
    insert into public.cart_registros (period_id, record_key, row_order, empresa, cnpj, dominio, responsavel_fiscal,
      responsavel_contabil, responsavel_depto_pessoal, regime, socios, fone, email, honorarios, situacao, obs,
      version, created_at, updated_at, updated_by)
    values (v_per.id, gen_random_uuid()::text, i, v_lim->>'empresa', v_lim->>'cnpj', v_lim->>'dominio',
      v_lim->>'responsavel_fiscal', v_lim->>'responsavel_contabil', v_lim->>'responsavel_depto_pessoal', v_lim->>'regime',
      v_lim->>'socios', v_lim->>'fone', v_lim->>'email', v_lim->>'honorarios', v_lim->>'situacao', v_lim->>'obs',
      1, public.cart_ts(now()), public.cart_ts(now()), v_usuario);
  end loop;
  perform public.cart_auditar(v_batch, v_per, null, v_usuario, 'Importação XLSX', 'Período completo',
    v_ant || ' registro(s)', i || ' registro(s) · arquivo ' || left(v_nome, 180), null, null);
  update public.cart_periodos set updated_at = public.cart_ts(now()) where id = v_per.id;
  perform public.hub_hist_registrar('Carteira de Clientes', 'Importou XLSX', v_per.period_key,
    'Competência ' || substr(v_per.period_key, 6, 2) || '/' || substr(v_per.period_key, 1, 4),
    jsonb_build_object('arquivo', left(v_nome, 180), 'antes', v_ant, 'importadas', i));
  return jsonb_build_object('ok', true, 'batch_uuid', v_batch, 'period_key', v_per.period_key, 'previous_records', v_ant, 'imported_records', i);
end;
$$;

-- ------------------------------------------------------------------------------------------- usuários (ADM)

create or replace function public.cart_usuarios()
returns jsonb language plpgsql security definer set search_path = public as $$
begin
  perform public.cart_exigir(true);
  return jsonb_build_object('ok', true, 'users', coalesce((
    select jsonb_agg(jsonb_build_object('id', p.id, 'username', coalesce(nullif(btrim(p.nome), ''), p.email), 'display_name', coalesce(p.nome, ''),
      'email', coalesce(p.email, ''), 'hub_admin', (to_jsonb(p)->>'role') = 'admin',
      'role', case when (to_jsonb(p)->>'role') = 'admin' then 'admin' when a.papel = 'admin' then 'admin' else 'viewer' end,
      'is_active', (to_jsonb(p)->>'role') = 'admin' or coalesce(a.papel, 'viewer') <> 'bloqueado')
      order by lower(coalesce(nullif(btrim(p.nome), ''), p.email)))
    from public.profiles p left join public.cart_acessos a on a.user_id = p.id
    where public.profile_is_active(p)), '[]'::jsonb));
end;
$$;

create or replace function public.cart_usuario_salvar(p_user uuid, p_papel text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_p public.profiles; v_ant text;
begin
  perform public.cart_exigir(true);
  if p_papel not in ('admin', 'viewer', 'bloqueado') then perform public.cart_erro(400, 'Perfil inválido.'); end if;
  select * into v_p from public.profiles where id = p_user;
  if not found or not public.profile_is_active(v_p) then perform public.cart_erro(404, 'Usuário não encontrado.'); end if;
  if (to_jsonb(v_p)->>'role') = 'admin' then
    perform public.cart_erro(400, 'Administradores do HUB são sempre ADM na Carteira.');
  end if;
  if p_user = auth.uid() then perform public.cart_erro(400, 'O ADM não pode alterar o próprio acesso.'); end if;
  select papel into v_ant from public.cart_acessos where user_id = p_user;
  insert into public.cart_acessos (user_id, papel, atualizado_em, atualizado_por) values (p_user, p_papel, now(), auth.uid())
  on conflict (user_id) do update set papel = excluded.papel, atualizado_em = excluded.atualizado_em, atualizado_por = excluded.atualizado_por;
  perform public.hub_hist_registrar('Carteira de Clientes', 'Alterou acesso', p_user::text,
    coalesce(nullif(btrim(v_p.nome), ''), v_p.email, 'usuário'),
    jsonb_build_object('de', coalesce(v_ant, 'viewer'), 'para', p_papel));
  return jsonb_build_object('ok', true);
end;
$$;

