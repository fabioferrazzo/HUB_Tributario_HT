-- summarize_record do servidor
create or replace function public.cart_resumo(r public.cart_registros)
returns text language plpgsql stable set search_path = public as $$
declare f text; v text; partes text[] := '{}';
begin
  foreach f in array public.cart_campos() loop
    v := regexp_replace(coalesce(to_jsonb(r)->>f, ''), '^\s+|\s+$', '', 'g');
    if v <> '' then partes := partes || (public.cart_rotulo(f) || ': ' || v); end if;
  end loop;
  return coalesce(nullif(array_to_string(partes, ' | '), ''), '(linha sem dados)');
end;
$$;

create or replace function public.cart_auditar(p_batch uuid, p_periodo public.cart_periodos, p_reg public.cart_registros,
  p_usuario text, p_acao text, p_campo text, p_antes text, p_depois text, p_vantes integer, p_vdepois integer)
returns void language sql security definer set search_path = public as $$
  insert into public.cart_auditoria (event_uuid, batch_uuid, period_id, period_key, record_id, record_key, username, action, field,
    old_value, new_value, version_before, version_after, occurred_at, server_instance, row_ref, empresa_snapshot, cnpj_snapshot, user_id)
  values (gen_random_uuid()::text, p_batch::text, p_periodo.id, p_periodo.period_key, p_reg.id, coalesce(p_reg.record_key, ''), p_usuario,
    p_acao, p_campo, coalesce(p_antes, ''), coalesce(p_depois, ''), p_vantes, p_vdepois, public.cart_ts(now()), 'hub-supabase',
    case when p_reg.id is not null and coalesce(p_reg.row_order, 0) <> 0 then 'Linha ' || p_reg.row_order else '' end,
    coalesce(p_reg.empresa, ''), coalesce(p_reg.cnpj, ''), auth.uid())
$$;

